    /** All questions available for [categoryId] (subject or exam). */
    fun poolFor(categoryId: String): List<Question> {
        byCategory[categoryId]?.let { return it }
        val subjects = examSyllabus[categoryId] ?: return all
        return subjects.flatMap { byCategory[it].orEmpty() }
    }

    /** A shuffled quiz of up to [count] questions for [categoryId]. */
    fun quizFor(categoryId: String, count: Int = 10, random: Random = Random.Default): List<Question> =
        poolFor(categoryId).shuffled(random).take(count)

    /**
     * The daily challenge: the same mixed set for everyone on a given day,
     * seeded by the epoch day so it changes every midnight.
     */
    fun dailyChallenge(epochDay: Long, count: Int = 10): List<Question> =
        all.shuffled(Random(epochDay)).take(count)

    /** Mock-test section for a subject category. */
    fun mockSectionFor(categoryId: String): String = when (categoryId) {
        "quantitative_aptitude", "logical_reasoning" -> "Aptitude"
        "gujarati_grammar", "english_language" -> "Language"
        "computer_knowledge" -> "Computer"
        else -> "General Studies"
    }

    val mockSections = listOf("General Studies", "Aptitude", "Language", "Computer")

    /** Full-length mock paper built from the whole bank, grouped by section. */
    fun mockPaper(random: Random = Random.Default): List<MockQuestion> {
        val sectionOrder = mockSections.withIndex().associate { it.value to it.index }
        return all
            .shuffled(random)
            .sortedBy { sectionOrder[mockSectionFor(it.categoryId)] ?: 0 }
            .mapIndexed { index, question ->
                MockQuestion(
                    id = index + 1,
                    section = mockSectionFor(question.categoryId),
                    topic = question.topicTag,
                    questionEn = question.questionEn,
                    questionGuj = question.questionGuj,
                    options = question.options,
                    correctIndex = question.correctIndex
                )
            }
    }
